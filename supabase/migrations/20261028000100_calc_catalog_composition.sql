-- =====================================================================
-- Nutrikal ERP + CRM — catalog products: serving, capsules per jar and composition
-- From the Product Catalogue v2.1 (PDF), matched on the codes of the catalog
-- Google Sheet, which stays the source of codes, names and prices (owner,
-- Oct 2026). The sheet sync never touches these columns; products added to
-- the sheet later have none until they are filled in.
--
-- Capsule products: Sales may change the number of capsules per jar on an
-- offer (30–180); the price per jar changes in proportion to the standard
-- count stored here (capsules_per_container).
--
-- Corrections to the PDF, confirmed by the owner:
--   Crypto Zen is NTL-LF110 and MindFuel NTL-LF109 (as in the sheet);
--   TH115 vitamin B2 1.4 mg and copper 1 mg (printed as mcg);
--   SP105 Creatine: 60 servings of 5 g.
-- SP110 Electrolytes: 90 g in the sheet, 30 × 5 g in the PDF: servings left empty.
--
--                         admin   sales   production
-- calc_catalog_products   read    read    —        (unchanged)
-- =====================================================================

alter table public.calc_catalog_products
  add column capsules_per_serving   integer check (capsules_per_serving > 0),
  add column capsules_per_container integer check (capsules_per_container > 0),
  add column serving_g              numeric check (serving_g > 0),
  add column servings_per_container integer check (servings_per_container > 0),
  -- Amount per serving: [{"name": "MSM", "amount": 200, "unit": "mg", "note": null}, …]
  add column composition            jsonb check (composition is null or jsonb_typeof(composition) = 'array');

comment on column public.calc_catalog_products.capsules_per_container is
  'Standard capsules per jar; the catalog price is for this count. Null: not a capsule product.';

